"""Assemble the final report: sections, ledger, JSON sidecar.

The markdown is what a radiologist reads; the ledger is what an auditor reads.
Both are produced from the same Sentence list, so they cannot drift: every
sentence in the markdown appears in the ledger with its evidence, and
`assert_grounded` guarantees there is no sentence in one that is absent from
the other.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field

from .grounding import Evidence, ReportCase, Sentence, assert_grounded
from .template import findings_section, impression_section, technique_sentence

# How a sentence's evidence is rendered in the ledger.
BANNER = {
    True: "**STATUS: AUTOMATED RELEASE** (gate-approved; not a radiologist report)",
    False: "**STATUS: DEFERRED TO RADIOLOGIST** (gate withheld release)",
}


@dataclass
class Report:
    case: ReportCase
    sentences: list[Sentence]
    vlm_phrases: list[str] = field(default_factory=list)
    vlm_rejected: list[tuple[str, str]] = field(default_factory=list)  # (phrase, reason)
    vlm_model: str | None = None

    # -- rendering ----------------------------------------------------------

    def markdown(self, include_ledger: bool = True) -> str:
        c = self.case
        lines = [
            f"# Automated MRI report -- {c.patient_id}",
            "",
            BANNER[c.accepted],
            "",
            f"- Cohort: {c.cohort}",
            f"- Case confidence: {c.confidence:.3f} (gate threshold {c.gate_threshold:.3f})",
            f"- Findings generator: calibrated fusion (structured findings)",
            f"- VLM: {self.vlm_model or 'not used (deterministic template only)'}",
            "",
        ]
        sections = self._sections()
        for title, sents in sections:
            lines.append(f"## {title}")
            lines.append("")
            for s in sents:
                lines.append(f"- {s.text}")
            lines.append("")

        if self.vlm_rejected:
            lines.append("## Vetted-out VLM phrases")
            lines.append("")
            for phrase, reason in self.vlm_rejected:
                lines.append(f"- ~~{phrase}~~ -- vetoed: {reason}")
            lines.append("")

        lines.append("---")
        lines.append("")
        lines.append(
            "*Generated by cgate report generation. Every statement above is "
            "traceable to a calibrated probability, an image-quality metric, or "
            "the gate decision; see the grounding ledger.*"
        )
        if include_ledger:
            lines.append("")
            lines.append("## Grounding ledger")
            lines.append("")
            lines.append("| # | sentence | evidence |")
            lines.append("|---|----------|----------|")
            for i, s in enumerate(self.sentences, start=1):
                ev = "; ".join(
                    f"`{e.source}`" + (f" {e.detail}" if e.detail else "")
                    for e in s.evidence
                )
                snip = s.text if len(s.text) <= 90 else s.text[:87] + "..."
                lines.append(f"| {i} | {snip} | {ev} |")
        return "\n".join(lines) + "\n"

    def to_json(self) -> str:
        c = self.case
        payload = {
            "patient_id": c.patient_id,
            "cohort": c.cohort,
            "released": bool(c.accepted),
            "confidence": float(c.confidence),
            "gate_threshold": float(c.gate_threshold),
            "predicted": {k: {"class": v[0], "p": v[1]} for k, v in c.predicted.items()},
            "weakest_critical": {
                "finding": c.weakest_critical[0],
                "class": c.weakest_critical[1],
                "p": c.weakest_critical[2],
            },
            "vlm_model": self.vlm_model,
            "vlm_phrases": list(self.vlm_phrases),
            "vlm_rejected": [
                {"phrase": p, "vetoed_by": r} for p, r in self.vlm_rejected
            ],
            "sentences": [
                {
                    "text": s.text,
                    "evidence": [{"source": e.source, "detail": e.detail} for e in s.evidence],
                }
                for s in self.sentences
            ],
        }
        return json.dumps(payload, indent=2)

    # -- internals ----------------------------------------------------------

    def _sections(self) -> list[tuple[str, list[Sentence]]]:
        tech = [technique_sentence()]
        find = findings_section(self.case)
        if self.vlm_phrases:
            from .grounding import Evidence as _Ev

            vlm = [
                Sentence(p, (_Ev("vlm", f"model={self.vlm_model or 'unknown'}"),))
                for p in self.vlm_phrases
            ]
            find = find + vlm
        imp = impression_section(self.case)
        return [("Technique", tech), ("Findings", find), ("Impression", imp)]


def render_report(
    case: ReportCase,
    vlm_phrases: list[str] | None = None,
    vlm_rejected: list[tuple[str, str]] | None = None,
    vlm_model: str | None = None,
) -> Report:
    """Build the report and verify the grounding contract before returning."""
    sentences: list[Sentence] = []
    report = Report(
        case=case,
        sentences=sentences,
        vlm_phrases=list(vlm_phrases or []),
        vlm_rejected=list(vlm_rejected or []),
        vlm_model=vlm_model,
    )
    for _, sents in report._sections():
        sentences.extend(sents)
    assert_grounded(sentences)
    return report
